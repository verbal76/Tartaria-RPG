import { useGameStore } from '../app/state/gameStore';
import { getRaces, getFactions } from '../app/engine/character';

describe('starter inventory (OTA-374)', () => {
  beforeAll(() => { console.log = () => {}; console.warn = () => {}; console.error = () => {}; });

  it('a new character starts with a Water Bottle', async () => {
    const store = useGameStore;
    await store.getState().hydrate();
    const race = getRaces()[0]!;
    const fac = getFactions()[0]!;
    await store.getState().startNewGame({ name: 'Stocked', raceId: race.id, factionId: fac.id });

    const inv = store.getState().player!.inventory;
    const bottle = inv.find((i) => i.name === 'Water Bottle');
    expect(bottle).toBeDefined();
    expect((bottle?.quantity ?? 0)).toBeGreaterThanOrEqual(1);
  });
});
